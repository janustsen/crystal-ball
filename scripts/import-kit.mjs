// Imports the modeled component kit into the app: copies each @3x material image into assets/materials, writes
// assets/materials/manifest.json in the kit's cb-component-kit.v1 schema, and generates src/materialFiles.ts (the
// static require map React Native needs). Images are re-encoded as palette PNG: about a third of the size, no visible change.
//   node scripts/import-kit.mjs [kit dir]     default /Users/janustsen/dev/archive/crystal-ball-components
// The iMac lane's manifest.json and the MacBook lane's macbook/kit/slices.json are merged; a state is its own entry
// named <material>-<state>. The kit describes cap placement in prose, so the placements below are its structured form.
import {mkdirSync,readFileSync,rmSync,writeFileSync} from 'node:fs';
import sharp from 'sharp';
import {join} from 'node:path';

const kit=process.argv[2]||'/Users/janustsen/dev/archive/crystal-ball-components',out='assets/materials';
const imac=JSON.parse(readFileSync(join(kit,'manifest.json'),'utf8'));
const macbook=JSON.parse(readFileSync(join(kit,'macbook/kit/slices.json'),'utf8'));
// MacBook piece → app material name (states as <material>-<state>), text ink where the piece is light.
const macbookNames={sheet:'sheet',modal:'modal',plan:'plan',plan_selected:'plan-selected',badge_ribbon:'badge-ribbon',input:'input',input_focus:'input-focused',
 tabbar:'tabbar',tabslot:'tabslot',cradle:'cradle',mic_idle:'mic',mic_listening:'mic-listening',mic_disabled:'mic-disabled',share_frame:'share-frame',receipt_card:'receipt-card'};
const macbookInk={'receipt-card':'#2A190C'};
const caps={
 'parchment-note':{'brass-tack':{anchor:'top-center',offset_pt:[0,14]}},
 // Overlapping the paper's corner by 30 pt.
 'parchment-note-error':{'wax-seal-broken':{anchor:'top-right',offset_pt:[6,-5]}},
 'vellum-card':{'wax-seal':{anchor:'bottom-center',offset_pt:[0,0]}},
 // Hangs from the selected plan's top edge near its right corner.
 'plan-selected':{'badge-ribbon':{anchor:'top-right',offset_pt:[-8,30]}},
};

rmSync(out,{recursive:true,force:true});mkdirSync(out,{recursive:true});
const materials={};
const add=async(name,source,entry)=>{const file=`${name}.png`;await sharp(source).png({palette:true,quality:92,effort:10,dither:.6}).toFile(join(out,file));materials[name]={file,...entry,...(caps[name]?{caps:caps[name]}:{})}};
for(const [name,e] of Object.entries(imac.materials)){
 const base={size_px:e.size_px};
 await add(name,join(kit,e.file),e.cap?{...base,cap:true}:{...base,insets_px:e.insets_px,outset_pt:e.outset_pt??0,fixed_height_pt:e.fixed_height_pt??null,text_color:e.text_color});
}
for(const [piece,e] of Object.entries(macbook)){
 const name=macbookNames[piece];if(!name)throw new Error(`Unmapped MacBook piece ${piece}`);
 const c=e.capInsets_px??{top:0,right:0,bottom:0,left:0};
 if(name==='badge-ribbon'){await add(name,join(kit,'macbook/kit',`${piece}.png`),{size_px:e.px,cap:true});continue}
 await add(name,join(kit,'macbook/kit',`${piece}.png`),{size_px:e.px,insets_px:{top:c.top,right:c.right,bottom:c.bottom,left:c.left},outset_pt:0,fixed_height_pt:null,...(macbookInk[name]?{text_color:macbookInk[name]}:{})});
}
writeFileSync(join(out,'manifest.json'),JSON.stringify({schema:'cb-component-kit.v1',source:kit,materials},null,1)+'\n');
writeFileSync('src/materialFiles.ts',`// Generated by scripts/import-kit.mjs: the bundled image for each material file.\nexport const materialFiles:Record<string,number>={\n${Object.values(materials).map(m=>` '${m.file}':require('../assets/materials/${m.file}'),`).join('\n')}\n};\n`);
console.log('%d materials: %s',Object.keys(materials).length,Object.keys(materials).join(' '));
